"""Generate temperature-to-linear-RGB cubic coefficients; no texture or spectral loop.

Planck spectra integrated over 380..780 nm, using the analytic CIE 1931 fit
in Wyman, Sloan, Shirley (2013), equation 4 and table 1:
https://jcgt.org/published/0002/02/01/paper.pdf
This script implements the equations; it does not embed the paper's sample code.
"""
from math import exp, expm1, log
from pathlib import Path

LO, HI, COUNT = 1000, 40000, 16
LOBES = (
    ((.362, 442, .0624, .0374), (1.056, 599.8, .0264, .0323), (-.065, 501.1, .049, .0382)),
    ((.821, 568.8, .0213, .0247), (.286, 530.9, .0613, .0322)),
    ((1.217, 437, .0845, .0278), (.681, 459, .0385, .0725)),
)

def spectrum_rgb(temperature):
    xyz = [0., 0., 0.]
    for wave in range(380, 781, 2):
        weight = .5 if wave in (380, 780) else 1.
        power = (560 / wave) ** 5 / expm1(14387768.77 / (wave * temperature))
        for channel, lobes in enumerate(LOBES):
            response = sum(a * exp(-.5 * ((wave - b) * (c if wave < b else d)) ** 2) for a, b, c, d in lobes)
            xyz[channel] += power * response * weight
    x, y, z = (v / xyz[1] for v in xyz)
    return (3.2404542*x - 1.5371385*y - .4985314*z,
            -.969266*x + 1.8760108*y + .041556*z,
            .0556434*x - .2040259*y + 1.0572252*z)

def normalized(rgb):
    rgb = [max(0., v) for v in rgb]
    return [v / max(rgb) for v in rgb]

step = log(HI/LO)/COUNT
values = [spectrum_rgb(LO*exp(i*step)) for i in range(COUNT+1)]
epsilon = .0001
slopes = [tuple((b-a)/(2*epsilon)*step for a,b in zip(
    spectrum_rgb(LO*exp(i*step-epsilon)), spectrum_rgb(LO*exp(i*step+epsilon)))) for i in range(COUNT+1)]
coefficients = []
for i in range(COUNT):
    a,m,b,n = values[i],slopes[i],values[i+1],slopes[i+1]
    coefficients.append((tuple(2*x+y-2*z+w for x,y,z,w in zip(a,m,b,n)),
                         tuple(-3*x-2*y+3*z-w for x,y,z,w in zip(a,m,b,n)),m,a))
error = 0.
for i in range(10001):
    t = LO * (HI/LO) ** (i/10000)
    coordinate = log(t/LO)/step
    index = min(max(int(coordinate),0),COUNT-1)
    f = coordinate-index
    value = normalized([((a*f+b)*f+c)*f+d for a,b,c,d in zip(*coefficients[index])])
    error = max(error, max(abs(a-b) for a,b in zip(value,normalized(spectrum_rgb(t)))))
assert error < .00005, error
def selection(start,end,indent='    '):
    if end-start==1:
        return '\n'.join(indent+name+'=float3('+','.join(format(v,'.9g') for v in vector)+');'
                         for name,vector in zip(('a','b','c','d'),coefficients[start]))
    middle=(start+end)//2
    return (indent+f'if(index<{middle}) {{\n'+selection(start,middle,indent+'    ')+'\n'+indent+'} else {\n'
            +selection(middle,end,indent+'    ')+'\n'+indent+'}')
text = '''// Generated by Documentation~/scripts/build-blackbody-coefficients.py.
float4 GraphBlackbody(float temperature)
{
    float coordinate=log2(clamp(temperature,1000,40000)*0.001)*(16.0/5.32192809489);
    int index=(int)clamp(floor(coordinate),0,15);
    float f=saturate(coordinate-index);
    float3 a,b,c,d;
''' + selection(0,COUNT) + '''
    float3 rgb=max(((a*f+b)*f+c)*f+d,0);
    return float4(rgb/max(max(rgb.r,rgb.g),max(rgb.b,1e-20)),1);
}
'''
target = Path(__file__).resolve().parents[2] / 'src/Shaders/GraphBlackbody.hlsl'
target.write_text(text,encoding='utf-8',newline='\n')
print(f'Blackbody: {COUNT} cubic segments, max normalized RGB approximation error {error:.8g}')
